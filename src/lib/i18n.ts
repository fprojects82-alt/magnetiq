export const DICTS: Record<Lang, Dict> = { en, ar };

export function getDict(lang: Lang): Dict {
  return DICTS[lang] ?? en;
}

/** Price label in the chosen language, e.g. "480 EGP" / "480 ج.م". */
export function money(amount: number, lang: Lang): string {
  return lang === "ar" ? `${amount.toLocaleString("en-US")} ج.م` : `${amount.toLocaleString("en-US")} EGP`;
}

/** Badges stored in the database are English; translate the built-in ones. */
export function badgeText(badge: string | null | undefined, lang: Lang): string | null {
  if (!badge) return null;
  if (lang !== "ar") return badge;
  if (badge === "Most popular") return "الأكثر طلباً";
  if (badge === "Best value") return "أوفر اختيار";
  const save = /^Save (\d+) EGP$/.exec(badge);
  if (save) return `وفّر ${save[1]} ج.م`;
  return badge;
}
